def lod(url, uit, soort, naam, *extra):
    exporteer(url, soort, uit / naam, "--linked_data_namespace", BASE, *extra)


def test_turtle_noemt_crunch_uml_als_commentaar_en_als_triple(model):
    url, _, uit = model
    lod(url, uit, "ttl", "model.ttl")
    assert regels(uit / "model.ttl")[0] == f"# {REGEL}"
    graaf = Graph().parse(uit / "model.ttl", format="turtle")
    assert (URIRef(BASE), RDF.type, OWL.Ontology) in graaf
    assert list(graaf.objects(URIRef(BASE), PAV.createdWith)) == [RELEASE]
    # Eén keer, op de ontologie die het bestand beschrijft; niet op elk domein.
    assert len(list(graaf.triples((None, PAV.createdWith, None)))) == 1


def test_rdf_xml_en_json_ld_noemen_crunch_uml(model):
    url, _, uit = model
    lod(url, uit, "rdf", "model.rdf")
    kop = regels(uit / "model.rdf")[:2]
    assert kop[0].startswith("<?xml") and kop[1] == f"<!-- {REGEL} -->"
    assert (URIRef(BASE), PAV.createdWith, RELEASE) in Graph().parse(uit / "model.rdf", format="xml")

    lod(url, uit, "json-ld", "model.jsonld")
    assert (URIRef(BASE), PAV.createdWith, RELEASE) in Graph().parse(uit / "model.jsonld", format="json-ld")


def test_shapes_bestand_noemt_crunch_uml_op_de_eigen_ontologie(model):
    url, _, uit = model
    lod(url, uit, "ttl", "model.ttl", "--lod_shapes_file", str(uit / "shapes.ttl"))
    assert regels(uit / "shapes.ttl")[0] == f"# {REGEL}"
    shapes = Graph().parse(uit / "shapes.ttl", format="turtle")
    assert list(shapes.subject_objects(PAV.createdWith)) == [(URIRef(BASE + "shapes/"), RELEASE)]
    ontologie = Graph().parse(uit / "model.ttl", format="turtle")
    assert list(ontologie.subject_objects(PAV.createdWith)) == [(URIRef(BASE), RELEASE)]


def test_dezelfde_export_geeft_dezelfde_bytes(model):
    url, _, uit = model
    lod(url, uit, "ttl", "een.ttl")
    lod(url, uit, "ttl", "twee.ttl")
    assert (uit / "een.ttl").read_bytes() == (uit / "twee.ttl").read_bytes()


