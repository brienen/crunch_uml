def test_stempel_komt_uit_een_bron():
    assert generator.label() == f"crunch_uml {VERSIE}"
    assert generator.generated_by() == REGEL
    assert generator.release_iri() == str(RELEASE)
    assert generator.as_dict() == {"name": "crunch_uml", "version": VERSIE, "url": generator.HOMEPAGE}
    assert generator.version_line().startswith(f"crunch_uml {VERSIE}")


def test_versieregel_noemt_de_commit_alleen_vanuit_een_checkout(monkeypatch):
    monkeypatch.setattr(generator, "producer_build", lambda: "pypi")
    assert generator.version_line() == f"crunch_uml {VERSIE}"
    monkeypatch.setattr(generator, "producer_build", lambda: "0123456789abcdef0123456789abcdef01234567")
    assert generator.version_line() == f"crunch_uml {VERSIE} (git 0123456789ab)"


@pytest.mark.parametrize("vlag", ["--version", "-V"])
def test_opdrachtregel_meldt_de_versie(capsys, vlag):
    with pytest.raises(SystemExit) as stop:
        cli.main([vlag])
    assert stop.value.code == 0
    assert capsys.readouterr().out.strip() == generator.version_line()


def test_help_noemt_de_versie(capsys):
    with pytest.raises(SystemExit):
        cli.main(["-h"])
    assert f"crunch_uml {VERSIE}" in capsys.readouterr().out


def test_elke_opdracht_logt_de_versie(model, caplog):
    url, _, uit = model
    with caplog.at_level(logging.INFO):
        exporteer(url, "json", uit / "model.json")
    assert generator.version_line() in caplog.messages
    assert f"Schema 'default' was imported with crunch_uml {VERSIE}." in caplog.messages


