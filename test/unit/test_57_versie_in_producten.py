def meta(pad):
    return dict(sql(pad, "SELECT key, value FROM crunch_uml_meta"))


def test_database_kent_de_versie_die_haar_maakte_en_het_laatst_schreef(model):
    url, pad, _ = model
    waarden = meta(pad)
    assert waarden["crunch_version_created"] == VERSIE
    assert waarden["crunch_version_last_write"] == VERSIE
    assert sql(pad, "SELECT crunch_version FROM crunch_uml_runs") == [(VERSIE,)]

    # Een oudere versie maakte de database; een transformatie van nu schrijft erin.
    sql(pad, "UPDATE crunch_uml_meta SET value = '0.8.6' WHERE key LIKE 'crunch_version_%'")
    assert cli.main(["-db_url", url, "transform", "-ttp", "copy", "-sch_to", "kopie", "-rt_pkg", ROOT_PACKAGE]) == 0
    _dispose_singleton()
    waarden = meta(pad)
    assert waarden["crunch_version_created"] == "0.8.6"
    assert waarden["crunch_version_last_write"] == VERSIE


def test_database_van_voor_088_krijgt_geen_verzonnen_maker(model):
    url, pad, uit = model
    sql(pad, "DELETE FROM crunch_uml_meta WHERE key LIKE 'crunch_version_%'")
    exporteer(url, "json", uit / "model.json")  # lezen alleen: niets erbij
    assert "crunch_version_created" not in meta(pad)
    assert "crunch_version_last_write" not in meta(pad)
    assert cli.main(["-db_url", url, "import", "-f", FIXTURE, "-t", "eaxmi"]) == 0
    _dispose_singleton()
    waarden = meta(pad)
    assert "crunch_version_created" not in waarden  # wie haar maakte is niet bekend
    assert waarden["crunch_version_last_write"] == VERSIE


def test_export_waarschuwt_bij_import_door_een_andere_versie(model, caplog):
    url, pad, uit = model
    sql(pad, "UPDATE crunch_uml_runs SET crunch_version = '0.8.6'")
    with caplog.at_level(logging.INFO):
        exporteer(url, "json", uit / "model.json")
    waarschuwingen = [r.getMessage() for r in caplog.records if r.levelno == logging.WARNING]
    assert any(
        "was imported with crunch_uml 0.8.6" in tekst and f"crunch_uml {VERSIE}" in tekst and "again" in tekst
        for tekst in waarschuwingen
    ), waarschuwingen


