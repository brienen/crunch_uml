"""
Elk product zegt welke crunch_uml het maakte (0.8.8).

Aanleiding: na een bugfix was niet vast te stellen of een export met de nieuwe
of de oude versie was gemaakt. De opdrachtregel gaf geen versienummer, en het
gegenereerde RDF noemde het programma niet. Nu:

* ``crunch_uml --version`` en de eerste logregel van elke opdracht;
* de database: ``crunch_version_created`` en ``crunch_version_last_write`` in
  ``crunch_uml_meta``, naast de versie per import in ``crunch_uml_runs``;
* een waarschuwing bij een export uit een schema dat met een andere versie
  is ingelezen;
* elk exportformaat dat er een plek voor heeft: een commentaarregel of een
  metadataveld, in Linked Data ook ``pav:createdWith`` op de ontologie.

De stempel bevat alleen de versie, geen build of tijdstip: dezelfde export
geeft dezelfde bytes.
"""

import glob
import json
import logging
import sqlite3

import pytest
from lxml import etree
from openpyxl import load_workbook
from rdflib import Graph, Namespace, URIRef
from rdflib.namespace import OWL, RDF

import crunch_uml
import crunch_uml.db as db
from crunch_uml import cli, generator

FIXTURE = "./test/data/MIM_LOD_Fixture.xml"
ROOT_PACKAGE = "EAPK_00000001_0000_4000_8000_00000000A001"
BASE = "https://voorbeeld.nl/lod/"
PAV = Namespace("http://purl.org/pav/")

VERSIE = crunch_uml.__version__
REGEL = f"Generated by crunch_uml {VERSIE} (https://github.com/brienen/crunch_uml)"
RELEASE = URIRef(f"https://github.com/brienen/crunch_uml/releases/tag/v{VERSIE}")


def _dispose_singleton():
    inst = db.Database._instance
    if inst is not None:
        try:
            inst.session.close()
        except Exception:  # noqa: S110 - best-effort teardown
            pass
        try:
            inst.engine.dispose()
        except Exception:  # noqa: S110 - best-effort teardown
            pass
        db.Database._instance = None


@pytest.fixture(autouse=True)
def _reset_database_singleton():
    _dispose_singleton()
    yield
    _dispose_singleton()


@pytest.fixture
def model(tmp_path):
    """Een database met het MIM-testmodel; geeft (db-url, pad, uitvoermap)."""
    pad = tmp_path / "model.db"
    url = f"sqlite:///{pad}"
    assert cli.main(["-db_url", url, "import", "-f", FIXTURE, "-t", "eaxmi", "-db_create"]) == 0
    _dispose_singleton()
    uit = tmp_path / "uit"
    uit.mkdir()
    return url, pad, uit


def sql(pad, statement, *params):
    con = sqlite3.connect(pad)
    try:
        rows = con.execute(statement, params).fetchall()
        con.commit()
    finally:
        con.close()
    return rows


def exporteer(url, soort, bestand, *extra):
    assert cli.main(["-db_url", url, "export", "-t", soort, "-f", str(bestand), *extra]) == 0
    _dispose_singleton()


def regels(pad):
    with open(pad, encoding="utf-8") as fh:
        return fh.read().splitlines()


def enig_bestand(patroon):
    gevonden = glob.glob(str(patroon))
    assert len(gevonden) == 1, f"{patroon}: {gevonden}"
    return gevonden[0]


