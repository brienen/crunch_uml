def test_eigen_template_kan_de_stempel_gebruiken(model, tmp_path):
    url, _, uit = model
    templates = tmp_path / "templates"
    templates.mkdir()
    (templates / "eigen.j2").write_text(
        "{{ generated_by }}|{{ crunch_uml_version }}|{{ crunch_uml_url }}", encoding="utf-8"
    )
    exporteer(url, "jinja2", uit / "eigen.txt", "-jtd", str(templates), "-jt", "eigen.j2")
    bestand = enig_bestand(uit / "eigen_Model Zorg.txt")
    assert regels(bestand) == [f"{REGEL}|{VERSIE}|{generator.HOMEPAGE}"]
