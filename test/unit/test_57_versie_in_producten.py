def test_json_noemt_crunch_uml_en_blijft_inleesbaar(model, tmp_path):
    url, _, uit = model
    exporteer(url, "json", uit / "model.json")
    with open(uit / "model.json", encoding="utf-8") as fh:
        data = json.load(fh)
    assert data["_generator"] == {"name": "crunch_uml", "version": VERSIE, "url": generator.HOMEPAGE}
    assert len(data["classes"]) == 6

    terug = tmp_path / "terug.db"
    assert (
        cli.main(["-db_url", f"sqlite:///{terug}", "import", "-f", str(uit / "model.json"), "-t", "json", "-db_create"])
        == 0
    )
    _dispose_singleton()
    assert sql(terug, "SELECT COUNT(*) FROM classes") == [(6,)]


def test_xlsx_noemt_crunch_uml_in_de_documenteigenschappen(model):
    url, _, uit = model
    exporteer(url, "xlsx", uit / "model.xlsx")
    werkboek = load_workbook(uit / "model.xlsx")
    assert werkboek.properties.creator == f"crunch_uml {VERSIE}"
    assert werkboek.properties.description == REGEL
    assert "classes" in werkboek.sheetnames and "_generator" not in werkboek.sheetnames


def test_xmi_noemt_crunch_uml_in_commentaar_en_blijft_inleesbaar(model, tmp_path):
    url, _, uit = model
    exporteer(url, "xmi", uit / "model.xml")
    wortel = etree.parse(str(uit / "model.xml")).getroot()
    commentaar = wortel.getprevious()
    assert commentaar is not None and commentaar.text.strip() == REGEL
    # EA herkent alleen zijn eigen export: de exporter-attributen blijven staan.
    documentatie = wortel[0]
    assert documentatie.get("exporter") == "Enterprise Architect"

    terug = tmp_path / "terug.db"
    assert (
        cli.main(["-db_url", f"sqlite:///{terug}", "import", "-f", str(uit / "model.xml"), "-t", "eaxmi", "-db_create"])
        == 0
    )
    _dispose_singleton()
    assert sql(terug, "SELECT COUNT(*) FROM classes WHERE name = 'Patient'") == [(1,)]


